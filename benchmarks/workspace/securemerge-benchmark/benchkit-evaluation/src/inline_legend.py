
def inline_legend(chart, label_pos=0.05, yoffsets=100):
    """Post-process a Seaborn axis for campaigns that use hue + style.

    This helper keeps only hue legend entries, inverts the x-axis, and adds
    inline labels on data lines. For style-based labels (for example
    ``initial_number_of_privileges``), labels are matched by a visual signature
    ``(linestyle, marker)`` rather than linestyle alone. This avoids mislabeled
    lines when multiple style values are present.

    The implementation of this function was generated by GPT-5.3-Codex.
    """

    import numpy as np
    from labellines import labelLines

    def _finite_xy(line):
        """Return finite x/y points for a line, or (None, None) if the line has no plottable data."""
        x_data = np.asarray(line.get_xdata(), dtype=float)
        y_data = np.asarray(line.get_ydata(), dtype=float)
        if x_data.size == 0 or y_data.size == 0:
            return None, None
        mask = np.isfinite(x_data) & np.isfinite(y_data)
        if not np.any(mask):
            return None, None
        return x_data[mask], y_data[mask]

    def _safe_label(text):
        """Keep only non-empty, user-visible labels (skip Matplotlib internal labels like _childN)."""
        return text if text and not text.startswith("_") else None

    def _line_signature(line):
        """Return a style signature that is stable for legend handles and real data lines."""
        return (line.get_linestyle(), line.get_marker())

    handles, labels = chart.get_legend_handles_labels()

    # Build a map from visual style signature to style label so unlabeled lines can still get inline text.
    style_by_signature = {}
    if "initial_number_of_privileges" in labels:
        i_style = labels.index("initial_number_of_privileges")

        for handle, label in zip(handles[i_style + 1:], labels[i_style + 1:]):
            style_by_signature[_line_signature(handle)] = label

    # Keep a compact legend with hue categories only (approach), because style is shown inline on lines.
    if "approach" in labels:
        i_approach = labels.index("approach")
        i_style = labels.index("initial_number_of_privileges") if "initial_number_of_privileges" in labels else len(
            labels)
        hue_handles = handles[i_approach + 1:i_style]
        hue_labels = labels[i_approach + 1:i_style]
        if hue_handles:
            if chart.legend_ is not None:
                chart.legend_.remove()
            chart.legend(hue_handles, hue_labels, title="approach")

    # Label each real data line directly in the plot.
    label_index = 1
    lines_to_label = []
    x_positions = []
    for line in chart.get_lines():
        x_data, y_data = _finite_xy(line)
        if x_data is None or y_data is None:
            continue

        raw_label = _safe_label(line.get_label())

        if raw_label is None:
            style = style_by_signature.get(_line_signature(line))

            if style is not None:
                raw_label = f"{style}"
            else:
                raw_label = f"line {label_index}"

        x_for_label = float(np.quantile(x_data, label_pos))
        line.set_label(raw_label)
        lines_to_label.append(line)
        x_positions.append(x_for_label)
        label_index += 1

    if lines_to_label:
        labelLines(
            lines_to_label,
            xvals=x_positions,
            backgroundcolor="none",
            outline_width=2,
            zorder=2.5,
            yoffsets=yoffsets
        )